<?php

namespace ForumFortress\Flarum\Listener;

use Flarum\Settings\Event\Deserializing;
use Flarum\Settings\Event\Saving;
use Flarum\Settings\SettingsRepositoryInterface;

/**
 * Keep service credentials server-side, including on Flarum's admin bootstrap.
 * Flarum 1.8 and 2.x both send settings->all() to the admin browser.
 */
final class AdminSecretSettings
{
    public function __construct(private SettingsRepositoryInterface $settings)
    {
    }

    public function handle(Deserializing|Saving $event): void
    {
        if ($event instanceof Deserializing) {
            $event->settings['forumfortress.api_key_configured'] =
                trim((string) $this->settings->get('forumfortress.api_key', '')) !== '' ? '1' : '0';
            unset(
                $event->settings['forumfortress.api_key'],
                $event->settings['forumfortress.bootstrap_recovery_token']
            );
            return;
        }

        // The indicator is display-only; never let the admin settings API
        // overwrite the bootstrap recovery token generated by the client.
        unset(
            $event->settings['forumfortress.api_key_configured'],
            $event->settings['forumfortress.bootstrap_recovery_token']
        );

        if (array_key_exists('forumfortress.api_key', $event->settings)) {
            $candidate = $event->settings['forumfortress.api_key'];
            if (! is_string($candidate) || trim($candidate) === '') {
                // Blank generic settings submissions must not erase credentials.
                unset($event->settings['forumfortress.api_key']);
            } elseif (preg_match('/[\r\n]/', $candidate)) {
                throw new \InvalidArgumentException('The Forum Fortress API key cannot contain newlines.');
            } else {
                // A non-empty password submission is an explicit replacement.
                $event->settings['forumfortress.api_key'] = trim($candidate);
            }
        }
    }
}
